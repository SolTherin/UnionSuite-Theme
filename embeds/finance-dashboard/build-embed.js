#!/usr/bin/env node
/**
 * build-embed.js — bundle a surface into ONE self-contained HTML fragment.
 *
 *   node build-embed.js            # builds every surface
 *   node build-embed.js dashboard  # or: run | arrears
 *   node build-embed.js --inline   # self-contained (CSS/JS inlined)
 *   node build-embed.js --plain    # without the Union Suite theme → dist/plain/
 *
 * Output: dist/<surface>-embed.html — a fragment with NO <html>/<head>/<body>,
 * ready to paste into an iMIS RiSE content record that already sits inside a
 * page div. CSS and JS are inlined, so nothing is fetched from Cloudflare Pages
 * and iMIS's stripping of domains from static tags never comes into play.
 *
 * ⚠ THIS IS A SNAPSHOT. The moment you edit fd-*.js or fd-styles.css, the
 *   pasted copy in iMIS is stale — re-run this and re-paste. That is the cost
 *   of the self-contained model vs the runtime-URL one (README "Deploying"),
 *   where a Pages push updates every embed at once.
 */
"use strict";
const fs   = require("fs");
const path = require("path");

const DIR = __dirname;
const OUT = path.join(DIR, "dist");

/* Which files each surface needs. Matches the loaders in the HTML shells —
   keep them in step. */
const SURFACES = {
  dashboard: { shell: "index.html",       scripts: ["fd-config.js", "fd-core.js", "fd-data.js", "fd-run.js", "fd-dashboard.js", "fd-theme-series.js", "fd-boot.js"] },
  run:       { shell: "payment-run.html", scripts: ["fd-config.js", "fd-core.js", "fd-data.js", "fd-run.js", "fd-theme-series.js", "fd-boot.js"] },
  arrears:   { shell: "arrears.html",     scripts: ["fd-config.js", "fd-core.js", "fd-data.js", "fd-arrears.js", "fd-theme-series.js", "fd-boot.js"] },
};

/* The Union Suite theme is the default since 16 Oct 2026: fd-theme-unionsuite.css
   after fd-styles.css, fd-theme-series.js before fd-boot.js (it patches
   FDCore's chart palette before the first render) — the same order as the
   shells. --plain drops both, for the original look, into its own folder so it
   never overwrites the real build. */
const THEME = {
  css:    "fd-theme-unionsuite.css",
  script: "fd-theme-series.js",
  fonts:  "https://fonts.googleapis.com/css2?family=Open+Sans:wght@400;600;700&family=Red+Hat+Display:wght@600;700;800&family=Inter:wght@400;500;600;700&display=swap",
};
const PLAIN_FONTS = "https://fonts.googleapis.com/css2?family=Source+Sans+3:wght@400;600;700;800&display=swap";

const read = f => fs.readFileSync(path.join(DIR, f), "utf8");

/* A literal </script> inside a JS string would close the tag early and break
   the page. Same for </style> in CSS. Neither appears today; guard anyway,
   because the failure is silent and baffling. */
const safeJs  = s => s.replace(/<\/script/gi, "<\\/script");
const safeCss = s => s.replace(/<\/style/gi,  "<\\/style");

const args   = process.argv.slice(2);
const plain  = args.includes("--plain");
const outDir = plain ? path.join(OUT, "plain") : OUT;
const fonts  = plain ? PLAIN_FONTS : THEME.fonts;
const css    = plain ? ["fd-styles.css"] : ["fd-styles.css", THEME.css];
const scriptsFor = spec => plain ? spec.scripts.filter(f => f !== THEME.script) : spec.scripts;

/* Pull just the .fd-root markup out of the shell — no doctype, no head, no
   body, and none of the shell's asset loader (everything is inline here). */

function extractMarkup(shellFile) {
  const html  = read(shellFile);
  const start = html.indexOf('<div class="fd-root"');
  const endTag = "</div><!-- /.fd-root -->";
  const end   = html.indexOf(endTag);
  if (start < 0 || end < 0) {
    throw new Error(`${shellFile}: could not find the .fd-root block — has the shell changed?`);
  }
  return html.slice(start, end + endTag.length);
}

/* The Pages origin the CDN build loads from. Must match FDConfig.cdn. */
const CDN = "https://hubfinancedashboard.pages.dev/";

const header = (surface, spec, kind, warning) =>
`<!-- ═══════════════════════════════════════════════════════════════════════
     Finance Dashboard — ${surface} surface — ${kind}${plain ? " — PLAIN (NO THEME)" : " — UNION SUITE THEME"}
     Generated ${new Date().toISOString().slice(0, 16).replace("T", " ")} by build-embed.js — DO NOT EDIT THIS FILE.
     Edit the source (${spec.shell}, ${css.join(", ")}, ${scriptsFor(spec).join(", ")})
     and re-run:  node build-embed.js ${surface}${plain ? " --plain" : ""}${kind === "SELF-CONTAINED" ? " --inline" : ""}

     Paste into an iMIS RiSE content record. No <html>/<head>/<body> — this is a
     fragment and expects to live inside an existing page div.
${warning}
     Before pasting, check fd-config.js:
       · mode           "auto" resolves to live inside iMIS
       · endpoints      the CloudToolz Flow path for this surface
       · imisPages      the RiSE page paths the surfaces navigate between
     ═══════════════════════════════════════════════════════════════════════ -->`;

/* ── DEFAULT BUILD: markup + a loader that pulls CSS/JS from Pages ──────────
   iMIS strips every on* attribute at save time, INCLUDING ones inside the text
   of a <script> block — measured 4 Sep 2026: 24 of 25 `onclick` in the inlined
   build were removed, breaking the run cards, KPI cards and filter chips that
   the render functions generate. Code fetched from Pages never passes through
   that pipeline, so it arrives intact. This is also the only build where a
   Pages push updates every embedded page at once. */
function buildCdn(surface) {
  const spec = SURFACES[surface];
  const markup = extractMarkup(spec.shell);

  const out = `${header(surface, spec, "CDN LOADER (recommended)", `
     CSS and JS load at runtime from ${CDN} — deliberately, NOT inlined:
     iMIS's attribute filter strips on* handlers from inside script blocks too,
     which breaks every runtime-generated button. Code served from Pages is
     never seen by that filter. It also means a Pages push updates every
     embedded page — no re-pasting.
`)}

${markup}

<script>
window.FD_SURFACE = ${JSON.stringify(surface)};
(function () {
  var CDN   = ${JSON.stringify(CDN)};
  var local = /^(localhost|127\\.0\\.0\\.1|\\[::1\\])$/.test(location.hostname) || location.protocol === "file:";
  var base  = local ? "" : CDN;

  /* A dynamically inserted <link rel=stylesheet> does NOT block the scripts
     below, so the app can render — and MEASURE — before these rules apply.
     fd-boot.js awaits this promise; the timeout stops a blocked CDN turning
     "unstyled for a moment" into "never renders". Themed there are two sheets,
     appended in order so the skin wins, and the promise waits on both. */
  window.__fdCssReady = Promise.all(${JSON.stringify(css)}.map(function (file) {
    var css = document.createElement("link");
    css.rel = "stylesheet";
    css.href = base + file;
    document.head.appendChild(css);
    return new Promise(function (resolve) {
      css.onload = css.onerror = resolve;
      setTimeout(resolve, 4000);
    });
  }));

  var font = document.createElement("link");
  font.rel = "stylesheet";
  font.href = ${JSON.stringify(fonts)};
  document.head.appendChild(font);

  /* iMIS already ships FontAwesome 6 on every RiSE page; only a dev server needs it. */
  if (!document.getElementById("__RequestVerificationToken") && !document.getElementById("__ClientContext")) {
    var fa = document.createElement("link");
    fa.rel = "stylesheet";
    fa.href = "https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.2/css/all.min.css";
    document.head.appendChild(fa);
  }

  ${JSON.stringify(scriptsFor(spec))}.forEach(function (file) {
    var s = document.createElement("script");
    s.src = base + file;
    s.async = false;          // preserve order: config → core → data → views → boot
    s.onerror = function () { console.error("Finance Dashboard: failed to load " + file); };
    document.head.appendChild(s);
  });
})();
</script>
`;
  return write(surface, "", out);
}

/* ── OPT-IN BUILD: everything inlined ──────────────────────────────────────
   Survives iMIS's save-time transformations as of 4 Sep 2026, because the app
   no longer contains anything they act on: no tag-shaped on* attributes
   anywhere (all delegated off data-fd-action), and no named HTML entities in
   any .js file. Both were breaking changes before — see test/FINDINGS.md.
   The CDN build is still preferred; this is the no-CDN fallback. */
function buildInline(surface) {
  const spec   = SURFACES[surface];
  const markup = extractMarkup(spec.shell);
  const styles = css.map(f => `/* ══ ${f} ══ */\n${safeCss(read(f))}`).join("\n\n");
  const js     = scriptsFor(spec).map(f => `/* ══ ${f} ══ */\n${safeJs(read(f))}`).join("\n\n");

  const out = `${header(surface, spec, "SELF-CONTAINED", `
     Everything is inlined — nothing is fetched from Cloudflare Pages. Use this
     only where Pages is unreachable; ${surface}-embed.html (the CDN build) is
     8 KB rather than ~130 KB and a Pages push updates every page at once.

     ⚠ Two rules keep this build alive under iMIS's save-time filter. Break
       either and it fails at parse time, taking the whole app with it:
         1. NO on* attribute in any markup, including markup built as a string
            inside a script. Use data-fd-action + the delegated binder in
            fd-boot.js.
         2. NO named HTML entity in any .js file. iMIS decodes them on save;
            a quote entity becomes a bare quote inside a string literal and is
            an immediate SyntaxError. Use numeric refs built at runtime.
       Both are verified by test/simulate-filter.js before you paste.
`)}

<style>
${styles}
</style>

${markup}

<script>
window.FD_SURFACE = ${JSON.stringify(surface)};
window.__fdCssReady = Promise.resolve();   // styles are inline: no race to lose
(function () {
  var f = document.createElement("link");
  f.rel = "stylesheet";
  f.href = ${JSON.stringify(fonts)};
  document.head.appendChild(f);
})();
</script>

<script>
${js}
</script>
`;
  return write(surface, "-inline", out);
}

function write(surface, suffix, out) {
  fs.mkdirSync(outDir, { recursive: true });
  const file = path.join(outDir, `${surface}-embed${suffix}.html`);
  fs.writeFileSync(file, out, "utf8");
  return { file, bytes: Buffer.byteLength(out, "utf8") };
}

const inline  = args.includes("--inline");
const named   = args.find(a => !a.startsWith("--"));
const wanted  = named ? [named] : Object.keys(SURFACES);

for (const s of wanted) {
  if (!SURFACES[s]) throw new Error(`Unknown surface "${s}". Use: ${Object.keys(SURFACES).join(" | ")}`);
  const r = (inline ? buildInline : buildCdn)(s);
  console.log(`${path.relative(DIR, r.file).padEnd(36)} ${(r.bytes / 1024).toFixed(0).padStart(5)} KB`);
}
if (!inline) console.log("\nCDN builds: fd-*.js, fd-styles.css" + (plain ? "" : " and fd-theme-unionsuite.css") +
                         " must be published to " + CDN);
