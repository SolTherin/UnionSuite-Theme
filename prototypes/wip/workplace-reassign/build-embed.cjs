// Builds Workplace-Reassign-Embed.html: the component CSS in a <style>
// block, the Query Template, then the Confirm/Cancel script, as one paste-in
// fragment. The three stay the maintained sources; rebuild after changing
// any of them.
//
//   node prototypes/wip/workplace-reassign/build-embed.cjs

'use strict';

const fs = require('fs');
const path = require('path');

const dir = __dirname;
const css = fs.readFileSync(path.join(dir, 'workplace-reassign.candidate.css'), 'utf8').trim();
const template = fs.readFileSync(path.join(dir, 'templates', 'Workplace-Reassign-Query-Template.html'), 'utf8').trim();
const script = fs.readFileSync(path.join(dir, 'workplace-reassign.js'), 'utf8').trim();

const output = [
  '<!-- Reassign workplace: confirm moving a workplace to a new employer.',
  '     Generated by build-embed.cjs from workplace-reassign.candidate.css,',
  '     templates/Workplace-Reassign-Query-Template.html and',
  '     workplace-reassign.js; edit those, not this.',
  '     Paste the whole file into a Query Template Display iPart\'s Query',
  '     Template field (one result). The IQA fields it needs are listed in',
  '     README.md. Works with or without the UnionSuite theme CSS. -->',
  '<style>',
  css,
  '</style>',
  '',
  template,
  '',
  '<script>',
  script,
  '</script>',
  ''
].join('\n');

const target = path.join(dir, 'Workplace-Reassign-Embed.html');
fs.writeFileSync(target, output);
console.log('Wrote ' + path.relative(process.cwd(), target));
