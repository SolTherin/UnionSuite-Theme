const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../src/frames.js'),'utf8').replace(/^import .*;\r?\n/gm,'').replace('export class FrameStore','class FrameStore');
const FrameStore=vm.runInNewContext(source+'\nFrameStore;');
let preference='dark',visible=false,received=[];
const parent={storageKey:'theme',getState:()=>({preference,storageAvailable:false})};
const child={storageKey:'theme',receive:(...args)=>received.push(args)};
const win={performance:{now:()=>0},UnionSuiteAppearance:parent,clearTimeout(){}};
const store=new FrameStore(win,{},()=>{});
const entry={page:{id:'one'},documentLoaded:true,state:'ready',presented:true,frame:{isConnected:true,contentWindow:{UnionSuiteAppearance:child},getBoundingClientRect:()=>({width:visible?500:0,height:visible?300:0})}};
store.entries.set('one',entry);
store.syncPresentation(entry);assert.equal(received.length,0);
visible=true;store.syncPresentation(entry);assert.deepEqual(received.pop(),['dark',false],'Previously presented retained frame receives dark on reveal');
preference='light';store.syncPresentation(entry);assert.deepEqual(received.pop(),['light',false]);
preference=null;store.syncAppearance(entry);assert.deepEqual(received.pop(),[null,false],'Device setting and unavailable storage are preserved');
child.storageKey='preview';store.syncAppearance(entry);assert.equal(received.length,0,'Separate preview namespace stays isolated');
delete entry.frame.contentWindow.UnionSuiteAppearance;assert.doesNotThrow(()=>store.syncAppearance(entry));
Object.defineProperty(entry.frame,'contentWindow',{get(){throw Error('Cross-origin')}});assert.doesNotThrow(()=>store.syncAppearance(entry));
console.log('Passed CCO appearance: hidden/revealed retained frame, latest light/dark/system preference, storage failure, namespace isolation and unavailable child.');
